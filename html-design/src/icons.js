const escape = (text) =>
  String(text).replace(
    /[&"<>]/g,
    (c) => ({ "&": "&amp;", '"': "&quot;", "<": "&lt;", ">": "&gt;" })[c],
  );
export function icon(name) {
  const nodes = icons[name];
  if (!nodes) throw new Error(`Unknown icon: ${name}`);
  return `<svg xmlns="http://www.w3.org/2000/svg" class="icon" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${nodes
    .map(
      ([tag, attrs]) =>
        `<${tag} ${Object.entries(attrs)
          .map(([k, v]) => `${k}="${escape(v)}"`)
          .join(" ")}/>`,
    )
    .join("")}</svg>`;
}
export function button(
  action,
  name,
  label,
  { text = "", cls = "", attrs = "" } = {},
) {
  return `<button type="button" data-act="${action}" class="${cls}" title="${escape(label)}" aria-label="${escape(label)}" ${attrs}>${icon(name)}${text ? `<span>${escape(text)}</span>` : ""}</button>`;
}
